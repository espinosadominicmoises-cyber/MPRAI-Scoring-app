def rank_min(values):
    """Competition ranking (1, 1, 3, ...) on EXACT values: only identical values tie."""
    return [1 + sum(1 for o in values if o > v) for v in values]


def merge_match_states(datasets):
    """Combine several match-state dicts into one.
    datasets: list of (label, dict). Returns (merged_dict, warnings).
    Competitors are matched by name (ignoring capitalisation); scores are simply added together.
    Raises ValueError if the files belong to different divisions."""
    warnings = []

    # Divisions are never combined
    divisions = {d["division"] for _, d in datasets if d.get("division")}
    if len(divisions) > 1:
        raise ValueError(f"These files are from different divisions ({', '.join(sorted(divisions))}). Divisions are not combined.")

    # Match settings: first file that has each setting wins
    merged = {"version": 2}
    for key in ["match_name", "match_date", "division", "num_stages", "stages"]:
        for _, d in datasets:
            if d.get(key):
                merged[key] = d[key]
                break

    logos = {}
    for side in ("left", "right"):
        for _, d in datasets:
            if (d.get("logos") or {}).get(side):
                logos[side] = d["logos"][side]
                break
    if logos:
        merged["logos"] = logos

    if len({d["match_name"] for _, d in datasets if d.get("match_name")}) > 1:
        warnings.append("The files have different match names. Using the first one; double-check you picked the right files.")

    base_stages = [(x.get("title"), x.get("paper"), x.get("steel")) for x in merged.get("stages", [])]
    for label, d in datasets:
        if d.get("stages"):
            this_stages = [(x.get("title"), x.get("paper"), x.get("steel")) for x in d["stages"]]
            if this_stages != base_stages:
                warnings.append(f"{label}: stage titles/targets differ from the others. Using the first file's stage setup.")

    # Roster: union by name
    roster, index = [], {}
    for label, d in datasets:
        for c in d.get("competitors", []):
            name = str(c.get("Competitor", "")).strip()
            if not name:
                continue
            k = name.lower()
            if k not in index:
                entry = dict(c)
                entry["Competitor"] = name
                for f in ["Cat", "Reg", "Cls", "Tag", "ICS"]:
                    entry.setdefault(f, "")
                entry.setdefault("Power", "Minor")
                entry["DQ"] = bool(entry.get("DQ", False))
                try:
                    entry["#"] = int(entry.get("#"))
                except (TypeError, ValueError):
                    entry["#"] = None
                index[k] = entry
                roster.append(entry)
            else:
                e = index[k]
                try:
                    other_num = int(c.get("#"))
                except (TypeError, ValueError):
                    other_num = None
                if other_num is not None and e["#"] is not None and other_num != e["#"]:
                    warnings.append(f"{name}: competitor # differs between files ({e['#']} vs {other_num}). Kept {e['#']}.")
                elif e["#"] is None and other_num is not None:
                    e["#"] = other_num
                for f in ["Cat", "Reg", "Cls", "Tag", "ICS"]:
                    if not e.get(f) and c.get(f):
                        e[f] = c[f]
                if c.get("DQ"):
                    e["DQ"] = True  # a DQ on any device stands
                if c.get("Power") and c["Power"] != e["Power"]:
                    warnings.append(f"{name}: Power factor differs between files ({e['Power']} vs {c['Power']}). Kept {e['Power']}.")
    # Numbers are never reassigned; only fill in a missing one with the next free number
    used = [e["#"] for e in roster if e["#"] is not None]
    next_free = max(used, default=0) + 1
    for e in roster:
        if e["#"] is None:
            e["#"] = next_free
            warnings.append(f"{e['Competitor']} had no competitor #. Assigned #{next_free}.")
            next_free += 1
    seen = {}
    for e in roster:
        if e["#"] in seen:
            warnings.append(f"Competitor # {e['#']} is used by both {seen[e['#']]} and {e['Competitor']}. Please fix one in the roster.")
        else:
            seen[e["#"]] = e["Competitor"]
    roster.sort(key=lambda e: e["#"])
    merged["competitors"] = roster

    # Scores: union by (stage, competitor)
    scores = {}
    known_stages = {x[0] for x in base_stages}
    unknown_stages = set()
    for label, d in datasets:
        for k, v in d.get("scores", {}).items():
            if "|||" not in k:
                continue
            stage, nm = k.split("|||", 1)
            canon = index.get(nm.strip().lower())
            if canon is None:
                warnings.append(f"{label}: a score for '{nm}' was skipped because that competitor isn't in any roster.")
                continue
            new_key = f"{stage}|||{canon['Competitor']}"
            if new_key in scores and scores[new_key] != v:
                warnings.append(f"{canon['Competitor']} has different scores for {stage} in more than one file. Kept the one from {label}.")
            scores[new_key] = v
            if known_stages and stage not in known_stages:
                unknown_stages.add(stage)
    for stg in sorted(unknown_stages):
        warnings.append(f"Scores exist for stage '{stg}', which isn't in the stage setup, so they won't show up.")
    merged["scores"] = scores
    return merged, warnings


