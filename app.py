def _text_width_in(text, bold, size_pt=None):
    size_pt = TABLE_FONT_PT if size_pt is None else size_pt
    table = _ARIAL_BOLD if bold else _ARIAL_REG
    units = sum(table[ord(ch) - 32] if 32 <= ord(ch) <= 126 else 556 for ch in str(text))
    return units / 1000 * size_pt / 72


# Printed logo sizes in cm as (width, height). Left = PPSA (rectangular), right = MPRAI (circle).
LOGO_BOX_CM = {"left": (2.74, 4.14), "right": (3.61, 3.61)}


def _add_logo(cell, logo_bytes, align, box_cm):
    """Insert the logo at exactly box_cm (w, h). A replacement logo with a different shape is
    scaled to fit inside that box instead (never stretched)."""
    box_w, box_h = box_cm
    w, h = Image.open(io.BytesIO(logo_bytes)).size
    if abs((w / h) - (box_w / box_h)) / (box_w / box_h) <= 0.02:
        out_w, out_h = box_w, box_h
    else:
        scale = min(box_w / w, box_h / h)
        out_w, out_h = w * scale, h * scale
    para = cell.paragraphs[0]
    para.alignment = align
    para.add_run().add_picture(io.BytesIO(logo_bytes), width=Cm(out_w), height=Cm(out_h))


def _fmt_cell(v):
    if isinstance(v, (float, np.floating)):
        return f"{v:.4f}"
    return str(v)


def build_word_docx(lines, df, logo_left=None, logo_right=None):
    """Build a real .docx: logos + title lines at the top, then the table.
    lines: list of (text, point_size, bold)."""
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Inches(PAGE_W_IN), Inches(PAGE_H_IN)
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Inches(PAGE_MARGIN_IN))
    usable_in = PAGE_W_IN - 2 * PAGE_MARGIN_IN

    no_spacing = doc.styles["No Spacing"]
    no_spacing.font.name = "Arial"
    no_spacing.font.size = Pt(TABLE_FONT_PT)   # also sizes the paragraph mark of EMPTY cells
    normal = doc.styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(10)
    normal.paragraph_format.space_before = Pt(0)
    normal.paragraph_format.space_after = Pt(0)

    def add_lines(container, align, first_para=None):
        for i, (text, size, bold) in enumerate(lines):
            para = first_para if (i == 0 and first_para is not None) else container.add_paragraph()
            para.alignment = align
            run = para.add_run(text)
            run.font.size, run.font.name, run.bold = Pt(size), "Arial", bold

    if logo_left or logo_right:
        side_w = 1.75   # inches; wide enough for a 3.61 cm logo plus cell padding
        hdr = doc.add_table(rows=1, cols=3)
        hdr.alignment = WD_TABLE_ALIGNMENT.CENTER
        hdr.autofit = False
        widths = [side_w, usable_in - 2 * side_w, side_w]
        for col, w in zip(hdr.columns, widths):
            col.width = Inches(w)          # sets the table grid (honoured by Word *and* LibreOffice)
        for cell, w in zip(hdr.rows[0].cells, widths):
            cell.width = Inches(w)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        if logo_left:
            _add_logo(hdr.rows[0].cells[0], logo_left, WD_ALIGN_PARAGRAPH.LEFT, LOGO_BOX_CM["left"])
        if logo_right:
            _add_logo(hdr.rows[0].cells[2], logo_right, WD_ALIGN_PARAGRAPH.RIGHT, LOGO_BOX_CM["right"])
        mid = hdr.rows[0].cells[1]
        add_lines(mid, WD_ALIGN_PARAGRAPH.CENTER, first_para=mid.paragraphs[0])
    else:
        add_lines(doc, WD_ALIGN_PARAGRAPH.LEFT)
    doc.add_paragraph().paragraph_format.space_after = Pt(6)

    # ---- data table
    # Alignment by column position (applies to the header cell too):
    # cols 2,3,4 right | col 5 left | everything else (1, 6, 7, 8, ...) centered
    right_idx, left_idx = {1, 2, 3}, {4}
    cols = list(df.columns)
    rows = [[_fmt_cell(v) for v in r] for r in df.itertuples(index=False, name=None)]
    fit_w = [
        max([_text_width_in(c, True)] + [_text_width_in(r[i], False) for r in rows]) + CELL_PAD_IN
        for i, c in enumerate(cols)
    ]
    col_w = list(fit_w)                       # every column fits its own contents...
    if len(cols) > 4:                         # ...except column 5 (Competitor), which absorbs the leftover width
        col_w[4] = max(usable_in - (sum(fit_w) - fit_w[4]), 1.0)

    table = doc.add_table(rows=1, cols=len(cols))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    for col, w in zip(table.columns, col_w):
        col.width = Inches(w)              # sets the table grid so column widths actually apply

    def fill(cell, text, width, align, bold=False, shade=None):
        cell.width = Inches(width)
        para = cell.paragraphs[0]
        para.style = doc.styles["No Spacing"]     # Word's "No Spacing" paragraph style
        para.alignment = align
        run = para.add_run(text)
        run.font.size, run.font.name, run.bold = Pt(TABLE_FONT_PT), "Arial", bold
        mark = OxmlElement("w:rPr")           # paragraph-mark formatting, so blank cells stay as short as the rest
        for tag in ("w:rFonts", "w:sz", "w:szCs"):
            el = OxmlElement(tag)
            if tag == "w:rFonts":
                el.set(qn("w:ascii"), "Arial")
                el.set(qn("w:hAnsi"), "Arial")
            else:
                el.set(qn("w:val"), str(int(round(TABLE_FONT_PT * 2))))   # Word stores sizes in half-points
            mark.append(el)
        para._p.get_or_add_pPr().append(mark)
        if shade:
            shd = OxmlElement("w:shd")
            shd.set(qn("w:val"), "clear")
            shd.set(qn("w:color"), "auto")
            shd.set(qn("w:fill"), shade)
            cell._tc.get_or_add_tcPr().append(shd)

    def align_for(i):
        if i in left_idx:
            return WD_ALIGN_PARAGRAPH.LEFT
        if i in right_idx:
            return WD_ALIGN_PARAGRAPH.RIGHT
        return WD_ALIGN_PARAGRAPH.CENTER

    for i, c in enumerate(cols):
        fill(table.rows[0].cells[i], str(c), col_w[i], align_for(i), bold=True, shade="F2F2F2")
    repeat = OxmlElement("w:tblHeader")           # repeat header row on every printed page
    repeat.set(qn("w:val"), "true")
    table.rows[0]._tr.get_or_add_trPr().append(repeat)

    for r in rows:
        cells = table.add_row().cells
        for i, v in enumerate(r):
            fill(cells[i], v, col_w[i], align_for(i))

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


